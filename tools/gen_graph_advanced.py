#!/usr/bin/env python3
"""
Generates include/graph_advanced.h and src/graph_advanced.c: the unified
(representation-independent) wrappers for the advanced algorithm library.

Every function in list_advanced.h whose first parameter is `const ListGraph *g`
(and that is not in MANUAL or HELD) becomes `graph_adv_<name>(Graph *g, ...)`,
which forwards to list_adv_<name> or matrix_adv_<name> depending on the
representation currently in use, then tells the observer what kind of work was
done.  Doc comments are taken from src/list_advanced.c.

Run from the repository root:   python3 tools/gen_graph_advanced.py
The functions in MANUAL (two graphs, or owned handles) are written by hand in
src/graph_build.c.
"""
import re

# Written by hand (they take two graphs, or return an owned handle).
MANUAL = {'subgraph_isomorphism', 'graph_isomorphism', 'dynconn_create', 'dynconn_destroy',
          'dynconn_connected', 'dynconn_components'}

# Advanced versions that add nothing over what the unified API already has
# (graph_pagerank, graph_floyd_warshall, graph_k_shortest_paths, graph_a_star)
# or only forward to it (centrality).  Deliberately not exposed.
HELD = {'pagerank', 'floyd_warshall', 'k_shortest_paths', 'astar', 'centrality'}

ITERATIVE = {'force_layout', 'gnn_forward', 'color_refinement', 'eigenvector_centrality'}
ALL_PAIRS = {'harmonic_centrality', 'johnson'}
ADJACENCY = {'crossing_count', 'crossing_number_heuristic', 'color_coding_path'}
WEIGHTED = {'longest_path', 'reverse_delete', 'widest_path', 'ida_star',
            'jump_point_search', 'zero_weight_cycle'}

def op_for(name):
    if name in ITERATIVE: return 'OP_ITERATIVE_RUN'
    if name in ALL_PAIRS: return 'OP_ALL_PAIRS_RUN'
    if name in ADJACENCY: return 'OP_ADJACENCY_RUN'
    if name in WEIGHTED:  return 'OP_WEIGHTED_RUN'
    return 'OP_ALGO_RUN'

TYPE_MAP = {'ListAdvPath': 'GraphPath', 'ListAdvHeuristic': 'GraphHeuristic'}

def rename(text):
    text = re.sub(r'\bListAdv\w*', lambda m: TYPE_MAP.get(m.group(0), 'GraphAdv' + m.group(0)[7:]), text)
    text = re.sub(r'\blist_adv_(\w+)', r'graph_adv_\1', text)
    text = re.sub(r'\bList(\w*)', r'Graph\1', text)
    text = re.sub(r'\bLIST_(\w+)', r'GRAPH_\1', text)
    text = re.sub(r'\blist_(\w+)', r'graph_\1', text)
    return text

hsrc = open('include/list_advanced.h').read()
csrc = open('src/list_advanced.c').read()

proto_re = re.compile(r'(?P<ret>ListStatus)\s+list_adv_(?P<name>\w+)\s*\((?P<args>[^;{]*?)\)\s*;', re.S)

def split_params(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == '(': depth += 1
        if ch == ')': depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip()); cur = ''
        else:
            cur += ch
    if cur.strip(): out.append(cur.strip())
    return out

def param_name(p):
    return re.search(r'(\w+)\s*(\[[^\]]*\])?\s*$', p).group(1)

def doc_for(name):
    m = re.search(r'(/\*\*\s*\n \* list_adv_%s\b.*?\*/)\s*\n(?:static )?[\w ]+\blist_adv_%s\(' % (name, name), csrc, re.S)
    return rename(m.group(1)) if m else None

hdr = ['''/*
 * graph_advanced.h — the advanced algorithm library behind the unified Graph handle.
 *
 * GENERATED by tools/gen_graph_advanced.py from list_advanced.h; do not edit
 * by hand (the functions at the end live in src/graph_build.c).
 *
 * Each function runs on whichever representation the graph currently uses and
 * tells the adaptive observer what kind of work it did.  The contracts are
 * those of list_advanced.h / matrix_advanced.h; the doc comments below are the
 * list implementation's.  Results are not cached.
 *
 * Failures: functions return a GraphStatus directly.  A NULL graph gives
 * GRAPH_ERR_INVALID_ARGUMENT.  Link with -lm.
 */

#ifndef GRAPH_ADVANCED_H
#define GRAPH_ADVANCED_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "graph.h"
#include "graph_results.h"
#include "graph_status.h"
#include "graph_types.h"
''']
cimpl = ['''/*
 * graph_advanced.c — GENERATED by tools/gen_graph_advanced.py; do not edit.
 * See graph_advanced.h.
 */

#include "graph_advanced.h"

#include "adjacency_list.h"
#include "adjacency_matrix.h"
#include "graph_internal.h"
#include "list_advanced.h"
#include "list_backend.h"
#include "matrix_advanced.h"
#include "matrix_backend.h"
''']

count = 0
for m in proto_re.finditer(hsrc):
    name, args = m.group('name'), split_params(m.group('args'))
    if name in MANUAL or name in HELD:
        continue
    if not args or not re.match(r'const ListGraph \*\w+$', args[0]):
        continue
    count += 1
    first = param_name(args[0])
    rest = args[1:]
    sig = 'GraphStatus graph_adv_%s(%s)' % (name, ', '.join(['Graph *%s' % first] + [rename(a) for a in rest]))
    doc = doc_for(name)
    hdr.append('\n' + (doc + '\n' if doc else '') + sig + ';\n')
    names = ''.join(', ' + param_name(a) for a in rest)
    cimpl.append('''
%s
{
    if (%s == NULL) {
        return graph_set_error(GRAPH_ERR_INVALID_ARGUMENT);
    }
    const GraphStatus ret_ = %s->be == matrix_backend()
                          ? matrix_adv_%s((const MatrixGraph *)%s->impl%s)
                          : list_adv_%s((const ListGraph *)%s->impl%s);
    graph_after_op(%s, %s);
    return ret_;
}
''' % (sig, first, first, name, first, names, name, first, names, first, op_for(name)))

hdr.append('''
/* ------------------------------------------------------------------ */
/*  Hand-written (src/graph_build.c)                                    */
/* ------------------------------------------------------------------ */

/** Does @pattern occur inside @target?  Same contract as list_adv_subgraph_isomorphism.
 *  Both graphs must be directed or both undirected; @target is converted
 *  temporarily if it uses the other representation. */
GraphStatus graph_adv_subgraph_isomorphism(Graph *pattern, Graph *target, bool induced,
                                           bool match_weights, int *mapping, bool *found);

/** Do @a and @b have the same structure (and, if @match_weights, equal edge weights)?
 *  Color refinement first, then exact search: much faster than graph_is_isomorphic
 *  on large graphs.  @mapping (optional, id_bound(a) entries) receives an isomorphism.
 *  The graphs must both be directed or both undirected (else *isomorphic = false);
 *  @b is converted temporarily if it uses the other representation. */
GraphStatus graph_adv_graph_isomorphism(Graph *a, Graph *b, bool match_weights,
                                        bool *isomorphic, int *mapping);

/** Frees the arrays inside @cycles and zeroes it.  Safe with NULL. */
void graph_adv_cycles_free(GraphAdvCycles *cycles);

/** Rebuild the path source -> target from the N x N `pred` array of graph_adv_johnson
 *  (pred[s*N+v] = vertex before v on the path from s).  Free with graph_path_free. */
GraphStatus graph_adv_apsp_path(const double *dist, const int *pred, size_t n,
                                int source, int target, GraphPath *out);

/** Rebuild a path from a parent array (BFS/Dijkstra style).  Free with graph_path_free. */
GraphStatus graph_adv_path_from_parents(const int *parent, size_t n, int source, int target,
                                        double cost, GraphPath *out);

/**
 * Connectivity tracker for a graph that changes.  Connectivity is WEAK (edge
 * directions are ignored).  The tracker borrows @g, which must outlive it, and
 * follows the graph through edits and through automatic representation
 * migrations: a query after a change rebuilds in O(V + E); on an unchanged
 * graph each query is O(alpha(V)).  NULL on NULL / allocation failure.
 */
typedef struct GraphAdvDynConn GraphAdvDynConn;

GraphAdvDynConn *graph_adv_dynconn_create(Graph *g);
void             graph_adv_dynconn_destroy(GraphAdvDynConn *dc);
GraphStatus      graph_adv_dynconn_connected(GraphAdvDynConn *dc, int u, int v, bool *connected);
GraphStatus      graph_adv_dynconn_components(GraphAdvDynConn *dc, size_t *count);

#endif /* GRAPH_ADVANCED_H */
''')
open('include/graph_advanced.h', 'w').write(''.join(hdr))
open('src/graph_advanced.c', 'w').write(''.join(cimpl))
print('generated', count, 'wrappers')
