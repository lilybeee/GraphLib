#!/usr/bin/env python3
"""
Generates include/graph_algorithms.h and src/graph_algorithms.c: the unified
(representation-independent) wrappers for the algorithm library.

Every function in list_algorithms.h whose first parameter is `const ListGraph *g`
(and that is not in MANUAL) becomes `graph_<name>(Graph *g, ...)`, which forwards
to list_<name> or matrix_<name> depending on the representation currently in
use, then tells the observer what kind of work was done.

Run from the repository root:   python3 tools/gen_graph_algorithms.py
The functions in MANUAL (they create or combine graphs) are written by hand in
src/graph_build.c.
"""
import re

MANUAL = {'transpose', 'transitive_closure', 'transitive_reduction', 'graph_copy',
          'induced_subgraph', 'graph_union', 'graph_intersection', 'graph_complement',
          'is_isomorphic'}

# Workload class reported to the observer (default: OP_ALGO_RUN).
ITERATIVE = {'pagerank', 'hits', 'eigenvector_centrality', 'core_numbers',
             'label_propagation', 'louvain', 'strongly_connected_components',
             'bellman_ford'}
ALL_PAIRS = {'closeness_centrality', 'betweenness_centrality', 'eccentricity',
             'diameter_radius', 'floyd_warshall', 'johnson', 'network_stats'}
ADJACENCY = {'triangle_count', 'clustering_coefficient', 'maximal_cliques', 'max_clique',
             'max_flow', 'min_cut', 'common_neighbors', 'jaccard', 'hamiltonian',
             'bipartite_matching'}
WEIGHTED = {'a_star', 'dijkstra_multi', 'zero_one_bfs', 'k_shortest_paths', 'mst_prim',
            'dag_longest_path', 'critical_path'}

def op_for(name):
    if name in ITERATIVE: return 'OP_ITERATIVE_RUN'
    if name in ALL_PAIRS: return 'OP_ALL_PAIRS_RUN'
    if name in ADJACENCY: return 'OP_ADJACENCY_RUN'
    if name in WEIGHTED:  return 'OP_WEIGHTED_RUN'
    return 'OP_ALGO_RUN'

src = open('include/list_algorithms.h').read()

def rename(text):
    text = re.sub(r'\blist_(\w+)', r'graph_\1', text)
    text = re.sub(r'\bList(\w*)', r'Graph\1', text)
    text = re.sub(r'\bLIST_(\w+)', r'GRAPH_\1', text)
    return text

# Walk the file: banners, doc comments and prototypes in order.
tok = re.compile(
    r'(?P<banner>/\* =+ \*/\n/\*\s+(?P<title>[^\n]*?)\s*\*/\n/\* =+ \*/)'
    r'|(?P<doc>/\*\*(?:(?!\*/).)*\*/)\s*\n(?P<dproto>[A-Za-z_][\w \*]*?\blist_\w+\s*\([^;{]*?\)\s*;)'
    r'|(?P<proto>^[A-Za-z_][\w \*]*?\blist_\w+\s*\([^;{]*?\)\s*;)',
    re.S | re.M)

entries = []   # (kind, ...)
for m in tok.finditer(src):
    if m.group('banner'):
        entries.append(('banner', m.group('title').strip()))
    else:
        proto = m.group('dproto') or m.group('proto')
        doc = m.group('doc') if m.group('doc') else None
        entries.append(('proto', doc, ' '.join(proto.split())))

def split_params(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == '(': depth += 1
        if ch == ')': depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip()); cur = ''
        else:
            cur += ch
    if cur.strip(): out.append(cur.strip())
    return out

def param_name(p):
    m = re.search(r'\(\*(\w+)\)', p)          # function pointer parameter
    if m: return m.group(1)
    return re.search(r'(\w+)\s*(\[[^\]]*\])?\s*$', p).group(1)

hdr = ['''/*
 * graph_algorithms.h — the algorithm library behind the unified Graph handle.
 *
 * GENERATED by tools/gen_graph_algorithms.py from list_algorithms.h; do not edit
 * by hand (the graph-building functions at the end live in src/graph_build.c).
 *
 * Each function runs on whichever representation the graph currently uses and
 * tells the adaptive observer what kind of work it did, so the library keeps
 * choosing the cheaper representation for the way you really use it.  Results
 * of these functions are not cached.  The contracts (argument meaning, array
 * sizes, which codes are returned) are those of list_algorithms.h /
 * matrix_algorithms.h; complexity notes below quote the list implementation.
 *
 * Failures: functions returning GraphStatus return the code directly; the
 * bool / size_t / double ones record it for graph_last_error().
 * A NULL graph gives GRAPH_ERR_INVALID_ARGUMENT.
 *
 * Link with -lm.
 */

#ifndef GRAPH_ALGORITHMS_H
#define GRAPH_ALGORITHMS_H

#include <stdbool.h>
#include <stddef.h>
#include <stdio.h>

#include "graph.h"
''']
cimpl = ['''/*
 * graph_algorithms.c — GENERATED by tools/gen_graph_algorithms.py; do not edit.
 * See graph_algorithms.h.
 */

#include "graph_algorithms.h"

#include <math.h>

#include "adjacency_list.h"
#include "adjacency_matrix.h"
#include "graph_internal.h"
#include "list_algorithms.h"
#include "list_backend.h"
#include "matrix_algorithms.h"
#include "matrix_backend.h"
''']

count = 0
for e in entries:
    if e[0] == 'banner':
        title = re.sub(r'^\d+\.\s*', '', e[1])
        hdr.append('\n/* ------------------------------------------------------------------ */\n'
                   '/*  %s */\n/* ------------------------------------------------------------------ */\n' % title)
        continue
    _, doc, proto = e
    m = re.match(r'(?P<ret>[A-Za-z_][\w \*]*?)\s*\b(?P<name>list_\w+)\s*\((?P<args>.*)\)\s*;$', proto)
    ret, lname, args = m.group('ret').strip(), m.group('name'), split_params(m.group('args'))
    name = lname[len('list_'):]
    if not args or not re.match(r'const ListGraph \*\w+$', args[0]) or name in MANUAL:
        continue
    count += 1
    first = param_name(args[0])
    rest = args[1:]
    fargs = ['Graph *%s' % first] + [rename(a) for a in rest]
    fret = rename(ret)
    sig = '%s graph_%s(%s)' % (fret, name, ', '.join(fargs))
    hdr.append('\n' + (rename(doc) + '\n' if doc else '') + sig + ';\n')
    names = [param_name(a) for a in rest]
    def call(prefix, T):
        return '%s_%s((const %sGraph *)%s->impl%s)' % (
            prefix, name, T, first, ''.join(', ' + n for n in names))
    if fret == 'GraphStatus':
        bad = 'return graph_set_error(GRAPH_ERR_INVALID_ARGUMENT);'
    elif fret == 'bool':
        bad = 'graph_set_error(GRAPH_ERR_INVALID_ARGUMENT);\n        return false;'
    elif fret == 'double':
        bad = 'graph_set_error(GRAPH_ERR_INVALID_ARGUMENT);\n        return INFINITY;'
    else:
        bad = 'graph_set_error(GRAPH_ERR_INVALID_ARGUMENT);\n        return 0;'
    cimpl.append('''
%s
{
    if (%s == NULL) {
        %s
    }
    const %s ret_ = %s->be == matrix_backend()
                          ? %s
                          : %s;
    graph_after_op(%s, %s);
    return ret_;
}
''' % (sig, first, bad, fret, first, call('matrix', 'Matrix'), call('list', 'List'), first, op_for(name)))

# hand-written part's declarations
hdr.append('''
/* ------------------------------------------------------------------ */
/*  Functions that build or combine graphs (src/graph_build.c)          */
/*                                                                      */
/*  Every graph handed back is a new Graph the caller must free with    */
/*  graph_destroy.  Results are created in the same representation as   */
/*  the input graph (generators take the representation explicitly).    */
/*  On failure *out is set to NULL and a GraphStatus is returned.       */
/* ------------------------------------------------------------------ */

GraphStatus graph_transpose(Graph *g, Graph **out);
GraphStatus graph_transitive_closure(Graph *g, Graph **out);
GraphStatus graph_transitive_reduction(Graph *g, Graph **out);
GraphStatus graph_induced_subgraph(Graph *g, const int *vertices, size_t count, Graph **out);
GraphStatus graph_complement(Graph *g, Graph **out);

/** Deep copy (same representation).  NULL on failure; see graph_last_error(). */
Graph *graph_copy(Graph *g);

/** @a and @b must both be directed or both undirected.  @b is converted
 *  temporarily if it uses the other representation. */
GraphStatus graph_union(Graph *a, Graph *b, Graph **out);
GraphStatus graph_intersection(Graph *a, Graph *b, Graph **out);
GraphStatus graph_is_isomorphic(Graph *a, Graph *b, bool *result, int *mapping);

/* Generators: parameters as in list_gen_* / matrix_gen_*, plus the representation
 * to start in.  NULL on failure; see graph_last_error(). */
Graph *graph_gen_erdos_renyi(GraphRep rep, size_t n, double p, unsigned long long seed,
                             bool directed, double wmin, double wmax);
Graph *graph_gen_barabasi_albert(GraphRep rep, size_t n, size_t m, unsigned long long seed);
Graph *graph_gen_grid(GraphRep rep, size_t rows, size_t cols);
Graph *graph_gen_path(GraphRep rep, size_t n, bool directed);
Graph *graph_gen_cycle(GraphRep rep, size_t n, bool directed);
Graph *graph_gen_star(GraphRep rep, size_t n);
Graph *graph_gen_complete(GraphRep rep, size_t n, bool directed);
Graph *graph_gen_random_dag(GraphRep rep, size_t n, double p, unsigned long long seed,
                            double wmin, double wmax);
Graph *graph_gen_random_tree(GraphRep rep, size_t n, unsigned long long seed);

/* Readers: the graph is created in representation @rep. */
GraphStatus graph_read_edge_list(FILE *in, bool directed, GraphRep rep, Graph **out);
GraphStatus graph_read_named_edge_list(FILE *in, bool directed, GraphRep rep, Graph **out,
                                       char ***names_out, size_t *count);
GraphStatus graph_load_binary(FILE *in, GraphRep rep, Graph **out);
void        graph_names_free(char **names, size_t count);

/* Representation-independent helpers (they do not take a graph). */
GraphStatus graph_hungarian(const double *cost, size_t rows, size_t cols,
                            int *assignment, double *total);
size_t graph_path_from_parent(const int *parent, size_t n, int src, int dst, int *path, size_t cap);
size_t graph_path_from_next(const int *next, size_t n, int u, int v, int *path, size_t cap);

#endif /* GRAPH_ALGORITHMS_H */
''')
open('include/graph_algorithms.h', 'w').write(''.join(hdr))
open('src/graph_algorithms.c', 'w').write(''.join(cimpl))
print('generated', count, 'wrappers')
